package com.iot.lostfoundapp;

import java.util.ArrayList;


/*
 * ============================================================
 * 물품 Repository 인터페이스
 * ============================================================
 *
 * Activity
 *    ↓
 * ItemService
 *    ↓
 * ItemRepository
 *    ↓
 * DatabaseHelper
 *
 * DatabaseHelper가 이 인터페이스의 메서드를 실제로 구현한다.
 *
 * ============================================================
 */
public interface ItemRepository {


    // =========================================================
    // 물품 등록
    // =========================================================

    boolean insertItem(
            Item item
    );


    // =========================================================
    // 전체 물품 조회
    // =========================================================

    ArrayList<Item> getAllItems();


    // =========================================================
    // LOST / FOUND 종류별 조회
    // =========================================================

    ArrayList<Item> getItemsByType(
            String type
    );


    // =========================================================
    // 사용자별 등록 물품 조회
    // =========================================================

    ArrayList<Item> getItemsByUserId(
            int userId
    );


    // =========================================================
    // 검색
    // =========================================================

    ArrayList<Item> searchItems(
            String keyword
    );


    // =========================================================
    // 검색 + 타입 + 카테고리 + 정렬
    // =========================================================

    ArrayList<Item> getFilteredItems(
            String keyword,
            String type,
            String category,
            String sortOrder
    );


    // =========================================================
    // ID로 상세 조회
    // =========================================================

    Item getItemById(
            int itemId
    );


    // =========================================================
    // ID 조회 별칭
    // =========================================================

    Item getItem(
            int itemId
    );


    // =========================================================
    // 물품 수정
    // =========================================================

    boolean updateItem(
            Item item
    );


    // =========================================================
    // 물품 삭제
    // =========================================================

    boolean deleteItem(
            int itemId
    );


    // =========================================================
    // 연결 가능한 FOUND 목록 조회
    // =========================================================

    ArrayList<Item> getAvailableFoundItems(
            int lostItemId
    );


    // =========================================================
    // LOST ↔ FOUND 연결
    // =========================================================

    boolean linkItems(
            int lostItemId,
            int foundItemId
    );


    // =========================================================
    // 습득자의 전달 메모 저장
    // =========================================================

    boolean saveHandoffNote(
            int itemId,
            String note
    );


    // =========================================================
    // 물품 수령 완료
    //
    // LOST + FOUND 두 레코드 삭제
    // =========================================================

    boolean finishAndDeleteMatchedItems(
            int lostItemId
    );


    // =========================================================
    // 일반 삭제 실행 취소
    // =========================================================

    boolean restoreDeletedItem(
            Item deletedItem,
            Item matchedItemBeforeDelete
    );
}